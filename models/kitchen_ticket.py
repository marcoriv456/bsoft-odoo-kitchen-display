from odoo import api, fields, models, _
from odoo.exceptions import AccessError, ValidationError


KITCHEN_STATES = [
    ("new", "Pendiente"),
    ("preparing", "Preparando"),
    ("ready", "Listo"),
    ("served", "Entregado"),
    ("cancelled", "Cancelado"),
]


class BsoftKitchenTicket(models.Model):
    """An immutable unit of kitchen work, independent from POS line records.

    POS replaces its order-line rows every time an open restaurant order is
    saved.  A ticket therefore stores the kitchen lifecycle separately and is
    linked to the stable POS order plus the line UUID supplied by the POS.
    """

    _name = "bsoft.kitchen.ticket"
    _description = "BSOFT Kitchen Ticket"
    _order = "ordered_at desc, id desc"

    order_id = fields.Many2one("pos.order", required=True, ondelete="cascade", index=True)
    source_line_uuid = fields.Char(required=True, index=True, copy=False)
    product_id = fields.Many2one("product.product", required=True, ondelete="restrict")
    product_name = fields.Char(required=True, copy=False)
    qty = fields.Float(required=True, copy=False)
    note = fields.Char(copy=False)
    station_id = fields.Many2one("bsoft.kitchen.station", index=True, copy=False)
    state = fields.Selection(KITCHEN_STATES, default="new", required=True, index=True, copy=False)
    ordered_at = fields.Datetime(required=True, default=fields.Datetime.now, index=True, copy=False)
    started_at = fields.Datetime(copy=False)
    ready_at = fields.Datetime(copy=False)

    _sql_constraints = [
        ("bsoft_kitchen_ticket_qty_positive", "CHECK(qty > 0)", "La cantidad debe ser positiva."),
    ]

    @api.model_create_multi
    def create(self, vals_list):
        tickets = super().create(vals_list)
        tickets._bsoft_notify()
        return tickets

    def write(self, vals):
        result = super().write(vals)
        if set(vals) & {"state", "station_id", "qty", "note"}:
            self._bsoft_notify()
        return result

    def _bsoft_notify(self):
        try:
            self.env["bus.bus"]._sendone(
                "bsoft_kitchen_display", "bsoft_kitchen_update", {"ids": self.ids}
            )
        except Exception:
            # Polling remains the delivery guarantee if the bus is unavailable.
            pass

    def action_bsoft_set_state(self, state):
        if state not in dict(KITCHEN_STATES):
            raise ValidationError(_("Estado de cocina no válido."))
        groups = [
            "bsoft_kitchen_display.group_kitchen_cook",
            "bsoft_kitchen_display.group_kitchen_manager",
            "bsoft_kitchen_display.group_kitchen_admin",
        ]
        actor = self.env["res.users"].browse(
            self.env.context.get("bsoft_kitchen_actor_id", self.env.uid)
        )
        if not any(actor.has_group(group) for group in groups):
            raise AccessError(_("No tienes permiso para cambiar el estado de cocina."))

        for ticket in self:
            if ticket.state in {"served", "cancelled"}:
                raise ValidationError(_("Un pedido terminado no puede cambiar de estado."))
            vals = {"state": state}
            if state == "preparing":
                vals["started_at"] = fields.Datetime.now()
            elif state == "ready":
                vals["ready_at"] = fields.Datetime.now()
            ticket.write(vals)
        return True


class PosOrder(models.Model):
    _inherit = "pos.order"

    def _bsoft_sync_kitchen_tickets(self):
        """Create tickets only for quantities not previously sent to kitchen.

        This method runs *after* Odoo has recreated ``self.lines``.  Existing
        tickets are found by their POS-provided line UUID, so a re-save of the
        same order leaves completed work completed; a new line/quantity creates
        only the additional work item.
        """
        # POS cashiers create/update orders but need not have kitchen access.
        # Kitchen tickets are generated by this trusted server-side projection.
        Ticket = self.env["bsoft.kitchen.ticket"].sudo()
        ticket_vals = []

        for order in self:
            tickets = Ticket.search([("order_id", "=", order.id)])
            source_line_uuids = set()
            for line in order.lines:
                if not line.uuid:
                    continue
                source_line_uuids.add(line.uuid)

                line_tickets = tickets.filtered(
                    lambda ticket: ticket.source_line_uuid == line.uuid
                )

                # A product substitution is a new kitchen request.  Retain
                # served history, but remove unfinished work for the old item.
                changed_product = line_tickets.filtered(
                    lambda ticket: ticket.product_id != line.product_id
                    and ticket.state not in {"served", "cancelled"}
                )
                if changed_product:
                    changed_product.write({"state": "cancelled"})
                # Tickets for a previous product are historical records, not
                # quantities of the replacement product.
                line_tickets = line_tickets.filtered(
                    lambda ticket: ticket.product_id == line.product_id
                )

                accounted_qty = sum(
                    line_tickets.filtered(lambda ticket: ticket.state != "cancelled").mapped("qty")
                )
                quantity_to_remove = accounted_qty - max(line.qty, 0)
                if quantity_to_remove > 0.000001:
                    # Only unstarted work is safe to withdraw automatically.
                    # Work already in progress remains visible to the cook.
                    pending = line_tickets.filtered(
                        lambda ticket: ticket.state == "new"
                    ).sorted(key=lambda ticket: ticket.id, reverse=True)
                    for ticket in pending:
                        removed_qty = min(ticket.qty, quantity_to_remove)
                        quantity_to_remove -= removed_qty
                        if ticket.qty - removed_qty <= 0.000001:
                            ticket.write({"state": "cancelled"})
                        else:
                            ticket.write({"qty": ticket.qty - removed_qty})

                if line.qty <= 0:
                    continue

                additional_qty = line.qty - accounted_qty
                if additional_qty <= 0.000001:
                    continue

                # Existing installations may have active legacy line states at
                # upgrade time.  Preserve them for the first generated ticket.
                initial_state = "new"
                if not line_tickets and line.kitchen_state in {"served", "cancelled"}:
                    initial_state = line.kitchen_state

                station = line.kitchen_station_id or line._bsoft_get_station()
                ticket_vals.append({
                    "order_id": order.id,
                    "source_line_uuid": line.uuid,
                    "product_id": line.product_id.id,
                    "product_name": line.full_product_name or line.product_id.display_name,
                    "qty": additional_qty,
                    "note": line.customer_note or line.kitchen_note or "",
                    "station_id": station.id if station else False,
                    "state": initial_state,
                })

            # A line removed by the cashier is absent from the next POS
            # payload.  Hide only work that has not been started yet.
            tickets.filtered(
                lambda ticket: ticket.source_line_uuid not in source_line_uuids
                and ticket.state == "new"
            ).write({"state": "cancelled"})

        if ticket_vals:
            Ticket.create(ticket_vals)

    @api.model
    def _process_order(self, order, draft, existing_order):
        order_id = super()._process_order(order, draft, existing_order)
        self.browse(order_id)._bsoft_sync_kitchen_tickets()
        return order_id
